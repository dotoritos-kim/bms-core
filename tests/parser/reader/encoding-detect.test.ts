import { describe, it, expect } from 'vitest';
import { read } from '../../../src/parser/modules/reader';

/**
 * Auto-detection between legacy encodings. GBK (and often Shift-JIS) decode
 * almost every EUC-KR byte sequence without errors, so "first valid decode
 * wins" turned every Korean chart into Chinese/half-width-kana garbage.
 * Byte fixtures were produced with iconv-lite.
 */
const bytes = (...b: number[]) => new Uint8Array(b);

// "#TITLE ★한국어 테스트★\n#ARTIST 작곡가\n#GENRE 韓國 POP\n" (EUC-KR, incl. hanja)
const KOREAN = bytes(
  0x23, 0x54, 0x49, 0x54, 0x4c, 0x45, 0x20, 0xa1, 0xda, 0xc7, 0xd1, 0xb1, 0xb9, 0xbe, 0xee, 0x20,
  0xc5, 0xd7, 0xbd, 0xba, 0xc6, 0xae, 0xa1, 0xda, 0x0a, 0x23, 0x41, 0x52, 0x54, 0x49, 0x53, 0x54,
  0x20, 0xc0, 0xdb, 0xb0, 0xee, 0xb0, 0xa1, 0x0a, 0x23, 0x47, 0x45, 0x4e, 0x52, 0x45, 0x20, 0xf9,
  0xdb, 0xcf, 0xd0, 0x20, 0x50, 0x4f, 0x50, 0x0a,
);

// "#TITLE テスト曲\n#ARTIST ｱｰﾃｨｽﾄ\n" (Shift_JIS, incl. half-width kana)
const JAPANESE = bytes(
  0x23, 0x54, 0x49, 0x54, 0x4c, 0x45, 0x20, 0x83, 0x65, 0x83, 0x58, 0x83, 0x67, 0x8b, 0xc8, 0x0a,
  0x23, 0x41, 0x52, 0x54, 0x49, 0x53, 0x54, 0x20, 0xb1, 0xb0, 0xc3, 0xa8, 0xbd, 0xc4, 0x0a,
);

// "#TITLE 中文测试歌曲\n#ARTIST 作曲家\n" (GBK)
const CHINESE = bytes(
  0x23, 0x54, 0x49, 0x54, 0x4c, 0x45, 0x20, 0xd6, 0xd0, 0xce, 0xc4, 0xb2, 0xe2, 0xca, 0xd4, 0xb8,
  0xe8, 0xc7, 0xfa, 0x0a, 0x23, 0x41, 0x52, 0x54, 0x49, 0x53, 0x54, 0x20, 0xd7, 0xf7, 0xc7, 0xfa,
  0xbc, 0xd2, 0x0a,
);

describe('reader: legacy encoding auto-detection', () => {
  it('detects EUC-KR (was decoded as GBK / Shift-JIS)', () => {
    const text = read(KOREAN);
    expect(text).toContain('#TITLE ★한국어 테스트★');
    expect(text).toContain('#ARTIST 작곡가');
    expect(text).toContain('#GENRE 韓國 POP');
  });

  it('detects a short EUC-KR title', () => {
    // "#TITLE 사랑" — two syllables only
    expect(read(bytes(0x23, 0x54, 0x49, 0x54, 0x4c, 0x45, 0x20, 0xbb, 0xe7, 0xb6, 0xfb))).toBe('#TITLE 사랑');
  });

  it('still detects Shift_JIS, including half-width kana', () => {
    const text = read(JAPANESE);
    expect(text).toContain('#TITLE テスト曲');
    expect(text).toContain('#ARTIST ｱｰﾃｨｽﾄ');
  });

  it('still detects GBK', () => {
    const text = read(CHINESE);
    expect(text).toContain('#TITLE 中文测试歌曲');
    expect(text).toContain('#ARTIST 作曲家');
  });

  it('UTF-8 and ASCII are unaffected', () => {
    expect(read(new TextEncoder().encode('#TITLE 한국어 テスト'))).toBe('#TITLE 한국어 テスト');
    expect(read(new TextEncoder().encode('#TITLE abc'))).toBe('#TITLE abc');
  });
});
